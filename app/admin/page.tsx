// Generates a unique id for manually-approved votes. Declared at module
// scope (outside the component) so the impure Date.now()/crypto call
// never happens during render — it's only ever invoked from inside an
// event handler (handleVerifyVote).
function generateManualTransactionId(index: number): string {
  const unique = typeof crypto !== 'undefined' && crypto.randomUUID ? crypto.randomUUID() : `${Date.now()}-${Math.random()}`;
  return `manual-${unique}-${index}`;
}

