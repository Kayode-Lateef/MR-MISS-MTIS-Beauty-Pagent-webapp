  const recalculateCategoryPlacements = async (categoryId: string, preferredWinnerContestantId?: number) => {
    const [resultsData, adminVotesData] = await Promise.all([
      adminRequest({ table: 'results', action: 'read' }),
      adminRequest({ table: 'admin_votes', action: 'read' })
    ]);

    const categoryResults = (resultsData || []).filter((result: Result) => result.category_id === categoryId);
    const categoryAdminVotes = (adminVotesData || []).filter((adminVote: AdminVote) => adminVote.category_id === categoryId);
    const adminTotals = new Map<number, number>();

    categoryAdminVotes.forEach((adminVote: AdminVote) => {
      adminTotals.set(
        adminVote.contestant_id,
        (adminTotals.get(adminVote.contestant_id) || 0) + (Number(adminVote.votes_to_add) || 0)
      );
    });

    const totalEffectiveVotes = categoryResults.reduce((sum: number, result: Result) => {
      return sum + (Number(result.total_votes) || 0) + (adminTotals.get(result.contestant_id) || 0);
    }, 0);

    const sortedResults = categoryResults
      .map((result: Result) => ({
        ...result,
        effective_votes: (Number(result.total_votes) || 0) + (adminTotals.get(result.contestant_id) || 0)
      }))
      .sort((a: Result, b: Result) => {
        if (preferredWinnerContestantId) {
          if (a.contestant_id === preferredWinnerContestantId) return -1;
          if (b.contestant_id === preferredWinnerContestantId) return 1;
        }
        const voteDifference = (b.effective_votes || 0) - (a.effective_votes || 0);
        return voteDifference || a.contestant_id - b.contestant_id;
      });

    const rankedResults = sortedResults.map((result: Result, index: number) => ({
      ...result,
      rank: index + 1
    }));

    await Promise.all(rankedResults.map((result: Result) => {
      const rank = result.rank;
      const votePercentage = totalEffectiveVotes > 0
        ? Number(((((result.effective_votes || 0) / totalEffectiveVotes) * 100).toFixed(2)))
        : 0;

      return adminRequest({
        table: 'results',
        action: 'update',
        id: result.id,
        data: {
          rank,
          vote_percentage: votePercentage,
          is_winner: rank === 1 && (result.effective_votes || 0) > 0,
          updated_at: new Date().toISOString()
        }
      });
    }));
  };

