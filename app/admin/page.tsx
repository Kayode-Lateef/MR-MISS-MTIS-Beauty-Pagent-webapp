// ============================================================================
// Site Content tab — lets the admin edit every piece of frontend copy
// (hero text, about section, contact details, social links, footer) from
// the dashboard, without touching Supabase directly. Backed by the generic
// `site_content` table via the same /api/admin CRUD the rest of this page
// uses; the public frontend reads it back via GET /api/site-content.
// ============================================================================
interface SiteContentField {
  id: string;
  section: string;
  label: string;
  value: string;
}

const SECTION_ORDER = ['branding', 'hero', 'about', 'contact', 'social', 'footer'];
const SECTION_TITLES: Record<string, string> = {
  branding: 'Branding',
  hero: 'Homepage Hero',
  about: 'About the Pageant',
  contact: 'Contact Information',
  social: 'Social Media Links',
  footer: 'Footer',
};

function SiteContentTab({ adminRequest, showSuccess, showError }: { adminRequest: (payload: Record<string, any>) => Promise<any>; showSuccess: (msg: string) => void; showError: (msg: string) => void; }) {
  const [fields, setFields] = useState<SiteContentField[]>([]);
  const [drafts, setDrafts] = useState<Record<string, string>>({});
  const [savingId, setSavingId] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    (async () => {
      try {
        const data = await adminRequest({ table: 'site_content', action: 'read' });
        const rows: SiteContentField[] = data || [];
        setFields(rows);
        const draftMap: Record<string, string> = {};
        rows.forEach((f) => { draftMap[f.id] = f.value; });
        setDrafts(draftMap);
      } catch (error: any) {
        showError(error.message || 'Failed to load site content');
      } finally {
        setLoading(false);
      }
    })();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const handleSave = async (field: SiteContentField) => {
    setSavingId(field.id);
    try {
      await adminRequest({ table: 'site_content', action: 'update', id: field.id, data: { value: drafts[field.id], updated_at: new Date().toISOString() } });
      setFields((prev) => prev.map((f) => (f.id === field.id ? { ...f, value: drafts[field.id] } : f)));
      showSuccess(`"${field.label}" updated!`);
    } catch (error: any) {
      showError(error.message || 'Failed to save');
    } finally {
      setSavingId(null);
    }
  };

  if (loading) {
    return (
      <div className="bg-white rounded-2xl p-6 shadow-sm flex items-center justify-center py-16">
        <Loader2 size={28} className="animate-spin text-mtis-gold" />
      </div>
    );
  }

  const bySection: Record<string, SiteContentField[]> = {};
  fields.forEach((f) => {
    if (!bySection[f.section]) bySection[f.section] = [];
    bySection[f.section].push(f);
  });

  const orderedSections = [
    ...SECTION_ORDER.filter((s) => bySection[s]),
    ...Object.keys(bySection).filter((s) => !SECTION_ORDER.includes(s)),
  ];

  return (
    <div className="space-y-6">
      <div className="bg-blue-50 border border-blue-200 rounded-xl p-4 text-sm text-blue-700">
        Edit any text shown on the public homepage — hero heading, about section, contact details, social links, and footer — without needing Supabase. Changes appear on the site as soon as they're saved.
      </div>
      {orderedSections.map((section) => (
        <div key={section} className="bg-white rounded-2xl p-6 shadow-sm">
          <h3 className="text-lg font-bold text-mtis-blue mb-4">{SECTION_TITLES[section] || section}</h3>
          <div className="space-y-4">
            {bySection[section].map((field) => {
              const isLong = field.value.length > 80 || field.id.includes('text') || field.id.includes('subtitle');
              const hasChanged = drafts[field.id] !== field.value;
              return (
                <div key={field.id}>
                  <label className="block text-sm font-medium mb-1 text-gray-700">{field.label}</label>
                  <div className="flex items-start gap-2">
                    {isLong ? (
                      <textarea
                        value={drafts[field.id] ?? ''}
                        onChange={(e) => setDrafts((prev) => ({ ...prev, [field.id]: e.target.value }))}
                        rows={3}
                        className="flex-1 px-4 py-2 border rounded-xl"
                      />
                    ) : (
                      <input
                        type="text"
                        value={drafts[field.id] ?? ''}
                        onChange={(e) => setDrafts((prev) => ({ ...prev, [field.id]: e.target.value }))}
                        className="flex-1 px-4 py-2 border rounded-xl"
                      />
                    )}
                    <button
                      onClick={() => handleSave(field)}
                      disabled={!hasChanged || savingId === field.id}
                      className={`px-4 py-2 rounded-xl text-white text-sm transition flex items-center gap-1 ${hasChanged ? 'bg-mtis-blue hover:bg-mtis-blue/90' : 'bg-gray-300 cursor-not-allowed'}`}
                    >
                      {savingId === field.id ? <Loader2 size={14} className="animate-spin" /> : <Save size={14} />}
                      Save
                    </button>
                  </div>
                </div>
              );
            })}
          </div>
        </div>
      ))}
    </div>
  );
}
